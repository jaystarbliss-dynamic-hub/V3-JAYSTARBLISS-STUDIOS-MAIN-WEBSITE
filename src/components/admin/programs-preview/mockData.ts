function createDemoProgram(
  id: string,
  input: Partial<PreviewProgramRecord> & { title: string; slug: string }
): PreviewProgramRecord {
  const base = normalizeProgramRecord(id, input);
  const deliveryFormat =
    input.deliveryFormat ||
    (base.deliveryMode?.toUpperCase().includes('PHYSICAL')
      ? 'PHYSICAL'
      : base.deliveryMode?.toUpperCase().includes('HYBRID')
      ? 'HYBRID'
      : 'ONLINE');

  const targetAudience = input.targetAudience || 'B2C';

  return {
    ...base,
    ...input,
    id,
    deliveryFormat,
    targetAudience,
    isSampleData: true,
    previousStatusBeforeArchive:
      input.previousStatusBeforeArchive ||
      (base.status === 'DRAFT' ? 'DRAFT' : 'PUBLISHED'),
  };
}

